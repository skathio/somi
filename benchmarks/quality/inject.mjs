#!/usr/bin/env node
// How often the quality gate catches what it is for. In a throwaway clone of a known-good repository it adds one known smell at a time
// to a source file, runs the gate on that change, and records whether the expected rule fired. Each smell starts from a clean HEAD.
//   node benchmarks/quality/inject.mjs <repo> [--files 10]
import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { parseArgs } from 'node:util';
import { TEST_FILE } from '../../scripts/lib/signals.mjs';
import { listFiles, snapshotTree } from '../../scripts/lib/git-tree.mjs';
import { qualityGate } from '../../scripts/lib/quality/gate.mjs';
import { DEFAULT_LIMITS } from '../../scripts/lib/quality/limits.mjs';
import { unitsOf } from '../../scripts/lib/quality/metrics.mjs';
import { importGraph } from '../../scripts/lib/quality/imports.mjs';
import { languageOf, parseSource } from '../../scripts/lib/quality/parse.mjs';

// The same folders the gate skips, so a smell is only ever injected where the gate looks.
const SKIPPED = /(^|\/)(node_modules|vendor|dist|build|coverage|fixtures?|__fixtures__|testdata|test-data|docs?|examples?|demos?|playgrounds?)\/|\.min\.js$|\.d\.ts$|config\./;
const lines = (n, body) => Array.from({ length: n }, (_, i) => body(i)).join('\n');
const append = (text) => ({ file, dir }) => { fs.appendFileSync(path.join(dir, file), `\n${text}`); return true; };
const SMELLS = {
  pyramid: { rule: 'depth', apply: append('export function somiInjectedPyramid(items, a, b) {\n  for (const x of items) {\n    for (const y of x.children) {\n      if (a) { if (b) { if (y.ok) { return y; } } }\n    }\n  }\n  return null;\n}\n') },
  long: { rule: 'lines', apply: append(`export function somiInjectedLong(input) {\n  const out = [];\n${lines(70, (i) => `  out.push(input.value${i} ?? ${i});`)}\n  return out;\n}\n`) },
  params: { rule: 'params', apply: append('export function somiInjectedParams(a, b, c, d, e, f) {\n  return [a, b, c, d, e, f].filter(Boolean);\n}\n') },
  options: { rule: 'options', apply: append('export function somiInjectedOptions({ a, b, c, d, e, f, g, h }) {\n  return [a, b, c, d, e, f, g, h].filter(Boolean);\n}\n') },
  suppression: { rule: 'suppression', apply: append('// eslint-disable-next-line no-console\nconsole.log("somi injected");\n') },
  split: { rule: 'file-added-cognitive', apply: append(lines(5, (i) => `export function somiInjectedPart${i}(a, b, c) {\n  if (a) { if (b) { if (c) { return ${i}; } } }\n  return -1;\n}`) + '\n') },
  clone: { rule: 'clone', apply: (t) => t.donor && append(t.donor)(t) },
  near_clone: { rule: 'clone', apply: (t) => t.nearDonor && append(t.nearDonor)(t) },
  generated: { rule: 'depth', mode: 'benchmark', apply: ({ file, dir }) => { const p = path.join(dir, file); fs.writeFileSync(p, `// @generated by hand\n${fs.readFileSync(p, 'utf8')}\nexport function somiInjectedHidden(items, a, b) {\n  for (const x of items) {\n    for (const y of x) {\n      if (a) { if (b) { if (y) { return y; } } }\n    }\n  }\n  return null;\n}\n`); return true; } },
  empty_catch: { rule: 'empty-catch', apply: append('export function somiInjectedSwallow(fn) {\n  try { return fn(); } catch {}\n  return null;\n}\n') },
  console: { rule: 'console', apply: append('export function somiInjectedDebug(x) {\n  console.log("somi", x);\n  return x;\n}\n') },
  unused: { rule: 'unused-binding', apply: append('export function somiInjectedUnused(a, b) {\n  const unused = a * 2;\n  return a;\n}\n') },
  pass_through: { rule: 'pass-through', apply: append('export function somiInjectedPass(a, b) {\n  return somiInjectedTarget(a, b);\n}\n') },
  unused_export: { rule: 'unused-export', apply: (t) => t.namedImporters && append('export const somiInjectedUnusedExport = 1;\n')(t) },
  // A module the target imports comes to import the target back, which closes a loop.
  cycle: { rule: 'cycle', apply: ({ dir, file, imported }) => {
    if (!imported) return false;
    const spec = path.posix.relative(path.posix.dirname(imported), file);
    fs.appendFileSync(path.join(dir, imported), `\nimport * as somiInjectedCycle from '${spec.startsWith('.') ? spec : `./${spec}`}';\nexport const somiInjectedLoop = () => somiInjectedCycle;\n`);
    return true;
  } },
};

const { values, positionals } = parseArgs({ allowPositionals: true, options: { files: { type: 'string' }, 'clone-tokens': { type: 'string' } } });
const limits = values['clone-tokens'] ? { ...DEFAULT_LIMITS, clones: { tokens: Number(values['clone-tokens']) } } : DEFAULT_LIMITS;
const source = path.resolve(positionals[0]);
const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'somi-inject-'));
const git = (...a) => execFileSync('git', ['-c', 'user.name=t', '-c', 'user.email=t@t', ...a], { cwd: dir, encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'], maxBuffer: 256 * 1024 * 1024 }).trim();
try {
  execFileSync('git', ['clone', '-q', '--local', '--no-hardlinks', source, dir], { stdio: 'ignore' });
  const head = git('rev-parse', 'HEAD');
  const all = listFiles(dir, head).filter((f) => ['javascript', 'typescript'].includes(languageOf(f)) && !TEST_FILE.test(f) && !SKIPPED.test(f));
  const step = Math.max(1, Math.floor(all.length / Number(values.files ?? 10)));
  const targets = all.filter((_, i) => i % step === 0).slice(0, Number(values.files ?? 10));
  // The donor for the copy is the largest function elsewhere in the repository that is valid code on its own, renamed, so it is a copy
  // and not the same declaration. A method or an arrow cut out of its surroundings does not parse alone, so the next one is tried.
  const donorFor = async (target) => {
    const candidates = [];
    for (const f of all.filter((x) => x !== target).slice(0, 200)) {
      const text = fs.readFileSync(path.join(dir, f), 'utf8');
      const parsed = await parseSource(f, text);
      for (const u of parsed?.tree ? unitsOf(parsed.tree, { file: f }) : []) if (u.lines >= 12 && u.lines <= 60) candidates.push({ ...u, text: text.split('\n').slice(u.start - 1, u.end).join('\n') });
      parsed?.tree?.delete();
    }
    for (const c of candidates.sort((a, b) => b.lines - a.lines)) {
      const alone = await parseSource('donor.ts', c.text);
      const ok = Boolean(alone?.tree) && alone.errors.length === 0;
      alone?.tree?.delete();
      if (ok) return `\n${c.text.replace(c.name, 'somiInjectedCopy')}\n`;
    }
    return null;
  };
  // The donor again with a line inserted every few lines of its body, wherever the result still parses, so no long stretch of it is an
  // exact copy: only a near-copy match can find it.
  const nearCopy = async (donor) => {
    if (!donor) return null;
    let rows = donor.replace('somiInjectedCopy', 'somiInjectedNear').split('\n');
    for (let at = rows.length - 4; at >= 3; at -= 5) {
      const tried = [...rows.slice(0, at), `  const somiInserted${at} = Date.now();`, ...rows.slice(at)];
      const parsed = await parseSource('near.ts', tried.join('\n'));
      if (parsed?.tree && parsed.errors.length === 0) rows = tried;
      parsed?.tree?.delete();
    }
    return rows.join('\n');
  };
  const texts = new Map(all.map((f) => [f, fs.readFileSync(path.join(dir, f), 'utf8')]));
  const graph = importGraph(texts, new Set(all));
  const namedImporters = (file) => {
    const users = [...graph.values()].flat().filter((e) => e.to === file);
    return users.length > 0 && users.every((e) => e.names !== null);
  };
  const results = [];
  for (const file of targets) {
    const donor = await donorFor(file);
    const target = { file, dir, donor, nearDonor: await nearCopy(donor), namedImporters: namedImporters(file), imported: (graph.get(file) ?? []).find((e) => !e.typeOnly)?.to };
    for (const [name, smell] of Object.entries(SMELLS)) {
      git('checkout', '-q', '--', '.');
      if (!smell.apply(target)) continue;
      const r = await qualityGate(dir, { from: head, to: snapshotTree(dir), limits, repoFiles: listFiles(dir, head), mode: smell.mode ?? 'project' });
      const found = [...r.violations, ...r.warnings];
      results.push({ file, smell: name, caught: found.some((v) => v.rule === smell.rule), rules: [...new Set(found.map((v) => v.rule))] });
    }
  }
  const by = {};
  for (const x of results) { by[x.smell] ??= { injected: 0, caught: 0 }; by[x.smell].injected += 1; by[x.smell].caught += x.caught ? 1 : 0; }
  process.stdout.write(`${JSON.stringify({ repo: path.basename(source), files: targets.length, by, missed: results.filter((x) => !x.caught) })}\n`);
} finally { fs.rmSync(dir, { recursive: true, force: true }); }
