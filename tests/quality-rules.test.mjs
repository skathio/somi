// The quality gate's second set of rules: what a change cannot opt out of, options objects, how far an old function may grow, files
// that only get longer, and anonymous functions traced through a change. Rules not yet calibrated report as warnings, not failures.
import { test } from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import { oldLine, listFiles, snapshotTree } from '../scripts/lib/git-tree.mjs';
import { qualityGate } from '../scripts/lib/quality/gate.mjs';
import { DEFAULT_LIMITS, limitsFor } from '../scripts/lib/quality/limits.mjs';
import { unitsOf } from '../scripts/lib/quality/metrics.mjs';
import { parseSource } from '../scripts/lib/quality/parse.mjs';

const repo = (t) => {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'somi-rules-'));
  t.after(() => fs.rmSync(dir, { recursive: true, force: true }));
  const git = (...args) => execFileSync('git', ['-c', 'user.name=t', '-c', 'user.email=t@t', ...args], { cwd: dir, encoding: 'utf8' });
  git('init', '-q');
  const write = (file, text) => { fs.mkdirSync(path.dirname(path.join(dir, file)), { recursive: true }); fs.writeFileSync(path.join(dir, file), text); };
  const commit = () => { git('add', '-A'); git('commit', '-qm', 'base'); };
  return { dir, git, write, commit };
};
const gate = async (r, opts = {}) => {
  const from = r.git('rev-parse', 'HEAD').trim();
  const to = snapshotTree(r.dir);
  return qualityGate(r.dir, { from, to, limits: limitsFor('pr'), now: '2031-01-01T00:00:00Z', repoFiles: listFiles(r.dir, to), ...opts });
};
const rules = (findings) => findings.map((f) => `${f.rule}:${f.file}`).sort();
const PYRAMID = (name) => `export function ${name}(xs, a, b) {\n  for (const x of xs) {\n    for (const y of x) {\n      if (a) { if (b) { if (y) { return y; } } }\n    }\n  }\n  return null;\n}\n`;

test('a line the change did not add is traced back to where it was, and an added one has no old place', () => {
  const hunks = [{ first: 3, count: 2, removed: 0 }, { first: 10, count: 0, removed: 4 }, { first: 20, count: 1, removed: 1 }];
  assert.equal(oldLine(hunks, 1), 1);
  assert.equal(oldLine(hunks, 3), null, 'added');
  assert.equal(oldLine(hunks, 5), 3, 'two lines were added above it');
  assert.equal(oldLine(hunks, 11), 13, 'and then four removed above it');
  assert.equal(oldLine(hunks, 20), null, 'a replaced line is added');
  assert.equal(oldLine(hunks, 21), 23);
});

test('a generated marker or a skipped folder cannot excuse code a benchmark adds, and a project reports what it skipped', async (t) => {
  const r = repo(t);
  r.write('src/a.js', 'export const a = 1;\n');
  r.write('src/old-gen.js', `// @generated by a tool\nexport const v = 1;\n`);
  r.commit();
  r.write('src/gen.js', `// @generated by me\n${PYRAMID('hidden')}`);
  r.write('examples/lib.js', PYRAMID('tucked'));
  r.write('src/old-gen.js', `// @generated by a tool\n${PYRAMID('regenerated')}`);
  r.write('tool.py', 'print(1)\n');
  const project = await gate(r);
  assert.equal(project.ok, true);
  assert.deepEqual(project.skipped.map((s) => `${s.file}:${s.reason}`).sort(), ['examples/lib.js:folder', 'src/gen.js:generated', 'src/old-gen.js:generated']);
  assert.deepEqual(project.uncovered, ['tool.py'], 'a language the gate cannot read is named, so a pass is not mistaken for a check');
  const bench = await gate(r, { mode: 'benchmark' });
  assert.deepEqual([...new Set(bench.violations.filter((v) => v.rule === 'depth').map((v) => v.file))].sort(), ['examples/lib.js', 'src/gen.js']);
  assert.deepEqual(bench.skipped.map((s) => s.file), ['src/old-gen.js'], 'a file that was generated before stays skipped');
});

test('names taken through a destructured parameter are counted, and too many is advice, not a failure', async (t) => {
  const units = async (code, file = 'x.js') => unitsOf((await parseSource(file, code)).tree, { file });
  assert.deepEqual((await units('function f({ a, b, c }, [d, e], g) {}')).map((u) => [u.params, u.options]), [[3, 5]]);
  assert.deepEqual((await units('function f({ a, b = 2, ...rest }: O, x: number) {}', 'x.ts')).map((u) => u.options), [3]);
  const r = repo(t);
  r.write('src/a.js', 'export const a = 1;\n');
  r.commit();
  r.write('src/a.js', 'export function build({ a, b, c, d, e, f, g }) {\n  return [a, b, c, d, e, f, g];\n}\n');
  const result = await gate(r);
  assert.equal(result.ok, true);
  assert.deepEqual(result.warnings.map((w) => [w.rule, w.value, w.limit]), [['options', 7, DEFAULT_LIMITS.function.options]]);
});

test('a function already over a limit may grow a little with a warning, but not past the growth limit', async (t) => {
  const r = repo(t);
  const big = (extra) => `export function legacy(xs, a, b) {\n  for (const x of xs) {\n    for (const y of x) {\n      if (a) { if (b) { if (y) { return y; } } }\n${extra}    }\n  }\n  return null;\n}\n`;
  r.write('src/a.js', big('      if (x) { return 1; } else if (a) { return 2; }\n'));
  r.commit();
  const branch = (n) => Array.from({ length: n }, (_, i) => `      if (x === ${i}) { return ${i}; }\n`).join('');
  r.write('src/a.js', big(`      if (x) { return 1; } else if (a) { return 2; }\n${branch(1)}`));
  const small = await gate(r);
  assert.ok(!small.violations.some((v) => v.rule === 'cognitive'), 'three more is within the growth limit');
  assert.ok(small.warnings.some((w) => w.rule === 'cognitive' && w.name === 'legacy'));
  r.write('src/a.js', big(`      if (x) { return 1; } else if (a) { return 2; }\n${branch(2)}`));
  const grown = (await gate(r)).violations.find((v) => v.rule === 'cognitive');
  assert.equal(grown.value - grown.before, 6, 'six more is past it');
  assert.equal(grown.limit, grown.before + DEFAULT_LIMITS.growth.cognitive);
});

test('an anonymous callback with lines added above it is still the old one', async (t) => {
  const r = repo(t);
  const callback = 'export const run = (xs, a, b) => xs.map((x) => {\n  for (const y of x) {\n    for (const z of y) {\n      if (a) { if (b) { if (z) { return z; } } }\n    }\n  }\n  return null;\n});\n';
  r.write('src/a.js', callback);
  r.commit();
  r.write('src/a.js', `export const one = 1;\nexport const two = 2;\n${callback.replace('return null;', 'return undefined;')}`);
  const result = await gate(r);
  assert.ok(!result.violations.some((v) => v.rule === 'depth'), 'an old callback no worse than before does not fail for having moved down');
  r.write('src/a.js', `export const one = 1;\n${callback.replace('return null;', 'return undefined;')}${callback.replace('run', 'again').replace('return z;', 'return x;')}`);
  assert.ok((await gate(r)).violations.some((v) => v.rule === 'depth' && v.line === 10), 'a new callback below it is new');
});

test('a file that crosses the line or function limits, or gains too many lines at once, is advice', async (t) => {
  const r = repo(t);
  r.write('src/a.js', 'export const a = 1;\n');
  r.commit();
  r.write('src/a.js', Array.from({ length: 45 }, (_, i) => `export function f${i}(a) {\n  return a + ${i};\n}\n`).join(''));
  const result = await gate(r, { limits: { ...limitsFor('commit'), file: { ...DEFAULT_LIMITS.file, lines: 100, added_lines: 100 }, clones: { tokens: 1000 } } });
  assert.equal(result.ok, true);
  assert.deepEqual(rules(result.warnings), ['file-added-lines:src/a.js', 'file-functions:src/a.js', 'file-lines:src/a.js']);
});

test('the clone comparison says when it stopped short of the whole repository', async (t) => {
  const r = repo(t);
  for (let i = 0; i < 4; i++) r.write(`src/f${i}.js`, `export const v${i} = ${i};\n`);
  r.commit();
  r.write('src/new.js', 'export function f(a) {\n  return a;\n}\n');
  const result = await gate(r, { maxRepoFiles: 2 });
  assert.deepEqual(result.warnings.filter((w) => w.rule === 'clone-scope').map((w) => [w.value, w.limit]), [[4, 2]]);
});
